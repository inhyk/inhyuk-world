// tips: [[제목, 글], ...] (rank 비결 ①②…), last: 맨 끝 장 [id, 제목, 글]
function longGrade(g, intro, parts, rank, tips, last) {
  const out = [];
  parts.forEach((part, k) => {
    let name, text, field, lessons, count = '';
    if (Array.isArray(part)) {
      const [key, list, guided] = part, kind = KIND[key], chains = list.map(p => p.chain), lo = Math.min(...chains), hi = Math.max(...chains);
      name = kind.name; field = kind.field;
      count = `${list.length}판 (${lo === hi ? `${lo}연쇄` : `${lo}~${hi}연쇄`})`;
      text = `${kind.say?.[g] ?? ''} ${count}.`;
      lessons = list.map((p, i) => (guided ? guidedPuzzle : kind.make)(`grad${g}-${key}${i + 1}`, i + 1, p));
    } else ({ name, text, field, lessons } = part);
    out.push(tipPage(`grad${g}-part${k + 1}`, k ? `${k + 1}부 · ${name}` : `졸업${g} · ${ORDINAL[g]} 졸업`, k ? text : `${intro} 1부는 ${name} ${count}부터!`, field), ...lessons);
  });
  tips.forEach(([title, text], i) => out.push(tipPage(`grad${g}-tip${i + 1}`, `${rank} 비결 ${MARK[i]} ${title}`, text, TIP_FIELDS[(i + g) % TIP_FIELDS.length])));
  out.push(tipPage(last[0], last[1], last[2], ['R.G.B.', 'YPYPYP']));
  return out;
}

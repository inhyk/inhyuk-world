    goal: { chain: p.chain, moves: 2 }, field: p.field, pairs: p.pairs, answer: p.answer,
    retry: told ? `아깝다! 먼저 ${first} 놓고, 그다음에 ${second} 놓아 봐.` : '아깝다! 연쇄가 중간에 끊겼어. 어느 색이 3개에서 멈춰 있는지 찾아봐.',

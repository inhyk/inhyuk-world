const COLOR = ['', '빨강', '초록', '파랑', '노랑', '보라'];
const COLUMN = ['맨 왼쪽 줄', '둘째 줄', '셋째 줄', '넷째 줄', '다섯째 줄', '맨 오른쪽 줄'];
// "넷째 줄에 세워서" / "셋째 줄과 넷째 줄에 눕혀서"
const where = ([x, rot]) => (rot === 1 ? `${COLUMN[x]}과 ${COLUMN[x + 1]}에 눕혀서` : `${COLUMN[x]}에 세워서`);

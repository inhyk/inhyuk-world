//   자리: 짝마다 숫자 두 개 (줄 0~5, 돌림 0 세워서 · 1 눕혀서 오른쪽으로 · 2 뒤집어 세워서 · 3 눕혀서 왼쪽으로)
//   필드: 여섯 줄을 / 로 나누고, 줄마다 바닥에서 위로 쌓인 뿌요 (O 는 방해 뿌요). 빈 필드에서 쌓는 순서(copy)는 필드가 비어 있다.
// 풀어 쓴 모양은 school-puzzles2.mjs 와 같다: { chain, pairs, answer, field(위에서 아래 줄 순서), garbage(방해 뿌요 수, 있을 때만) }
// 이름은 종류 + 등급 (find6 = 졸업6 의 발화점 찾기). flat 눕혀서 발화, duo 두 색 발화, flip 뒤집어서 두 색 발화, two ~ seven 두 수 ~ 일곱 수 퍼즐,
// dig 방해 뿌요 속 발화점, digflat 방해 뿌요 속 눕혀서 발화, digtwo 방해 뿌요 속 두 수 퍼즐, copy 보고 따라 쌓기(빈 필드에서 쌓는 순서), mega 초대연쇄.
// 진짜 판(Player)으로 풀리는지는 tutorial.test.mjs 가 확인한다. 판을 바꾸면 그 시험도 다시 돌린다.
const COLOR = { R: 1, G: 2, B: 3, Y: 4, P: 5 };
function board(text) {
  const [chain, pairs, answer, cols] = text.split(';');
  const columns = cols.split('/'), top = Math.max(...columns.map(c => c.length)), garbage = cols.split('O').length - 1;
  return {
    chain: Number(chain),
    pairs: pairs.match(/../g).map(([a, c]) => [COLOR[a], COLOR[c]]),
    answer: answer.match(/../g).map(([x, rot]) => [Number(x), Number(rot)]),
    field: Array.from({ length: top }, (_, i) => columns.map(c => c[top - 1 - i] || '.').join('')),
    ...(garbage ? { garbage } : {}),
  };
}

// Writes the level names, difficulty labels and songs that the engine and the
// page need, from LEVELS in generate.mjs:
//   engine/include/LevelList.h                          (level select, songs)
//   public/play/dash-overdrive/classic/level-list.js    (page picker, online race)
// node games/dash-overdrive/classic/levels/level-list.mjs
import {writeFileSync} from 'node:fs';
import {LEVELS, LEVEL_TOTAL} from './generate.mjs';

// levels 1-21 were labelled by hand; 22-100 carry their own difficulty
const FIRST = ['easy', 'easy', 'normal', 'normal', 'hard', 'hard', 'hard', 'harder', 'harder', 'harder',
  'insane', 'insane', 'insane', 'demon', 'demon', 'secret', 'secret', 'secret', 'secret', 'secret', 'harder'];
export const LIST = LEVELS.map((spec, index) => ({name: spec.name, difficulty: FIRST[index] ?? spec.difficulty, song: spec.song ?? index}));

const label = key => key[0].toUpperCase() + key.slice(1);
const quote = text => JSON.stringify(text);

export function header() {
  return `#pragma once
// Generated by games/dash-overdrive/classic/levels/level-list.mjs from levels/generate.mjs. Do not edit.
#include "Config.h"
#include <array>
#include <string_view>

namespace LevelList {

static_assert(Config::LEVEL_COUNT == ${LEVEL_TOTAL}, "run levels/level-list.mjs");
// level names; the last slot is the map maker
constexpr std::array<std::string_view, Config::SLOT_COUNT> NAMES = {
    ${[...LIST.map(level => quote(level.name)), quote('My Level')].join(', ')}
};
constexpr std::array<std::string_view, Config::SLOT_COUNT> DIFFICULTIES = {
    ${[...LIST.map(level => quote(label(level.difficulty))), quote('Map Maker')].join(', ')}
};
// which song (public/play/dash-overdrive/classic/music/<song>.ogg) each level plays
constexpr std::array<int, Config::LEVEL_COUNT> SONGS = {
    ${LIST.map(level => level.song).join(', ')}
};

}
`;
}

export function script() {
  return `// Generated by games/dash-overdrive/classic/levels/level-list.mjs from levels/generate.mjs. Do not edit.
// [name, difficulty, song] for levels 1-${LEVEL_TOTAL}
window.CLASSIC_LEVEL_LIST = ${JSON.stringify(LIST.map(level => [level.name, level.difficulty, level.song]))};
`;
}

if (process.argv[1] && new URL(import.meta.url).pathname === process.argv[1]) {
  writeFileSync(new URL('../engine/include/LevelList.h', import.meta.url), header());
  writeFileSync(new URL('../../../../public/play/dash-overdrive/classic/level-list.js', import.meta.url), script());
  console.log(`level list written: ${LIST.length} levels`);
}

// npm install --prefix tools, then run with the local Vite server running.
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || '../../tools/node_modules/playwright/index.mjs');
import { mkdir } from 'node:fs/promises';
const out = process.argv[3] || new URL('../../artifacts/fat-tycoon', import.meta.url).pathname;
const origin = process.argv[2] || 'http://127.0.0.1:5197/';
const url = new URL(origin); url.searchParams.set('debug', '1');
await mkdir(out,{recursive:true});
const browser=await chromium.launch({headless:true,args:['--use-angle=metal','--enable-gpu','--ignore-gpu-blocklist']});
const page=await browser.newPage({viewport:{width:1280,height:760}});
const errors=[]; page.on('pageerror',e=>errors.push(String(e)));
await page.goto(url.href);
await page.waitForFunction(()=>window.__fat);
await page.screenshot({path:out+'/menu.png'});
await page.locator('#m-start').evaluate(e=>e.click());
for(let i=0;i<4;i++) await page.locator('#story-next').click();
await page.waitForFunction(()=>!document.querySelector('#hud').hidden);
await page.locator('#b-daily').click();
await page.getByRole('button',{name:/오늘 보상 받기/}).click();
await page.getByRole('button',{name:'내일 또 와요!'}).isDisabled().then(ok=>{if(!ok)throw Error('daily duplicate');});
await page.locator('#panel-close').click();
await page.evaluate(()=>window.__fat.pos.set(5.05,0,-15.55));
await page.waitForFunction(()=>!document.querySelector('#prompt').hidden);
await page.keyboard.press('KeyE');
await page.waitForFunction(()=>window.__fat.save.plate===20);
await page.locator('#game').click({position:{x:640,y:450}});
await page.waitForFunction(()=>window.__fat.save.plate===19);
await page.evaluate(()=>window.__fat.pos.set(0,0,7.5));
await page.waitForTimeout(500); await page.screenshot({path:out+'/play.png'});
await page.evaluate(()=>{const f=window.__fat,s=f.save;s.weight=f.C.STAGES[0].target;f.save=s;f.pos.set(0,0,-3)});
await page.waitForTimeout(100);await page.keyboard.press('KeyE');
await page.waitForFunction(()=>window.__fat.save.stage===1);
await page.reload();await page.waitForFunction(()=>window.__fat?.save.stage===1);
await page.locator('#m-start').evaluate(e=>e.click());
await page.evaluate(()=>{const f=window.__fat,s=f.C.newSave();s.intro=true;s.weight=f.C.STAGES[9].target;s.stage=9;f.save=s;f.pos.set(0,0,-3)});
await page.waitForTimeout(100);await page.keyboard.press('KeyE');
await page.locator('#cert-ok').click();
await page.waitForFunction(()=>window.__fat.save.cleared[0]);
// 포탈 안으로 걸어 들어가면 월드 고르는 창이 뜬다. 월드 2~5를 차례로 깨고 넘어간다.
const names=['night','ice','space','gold'];
for(let w=2;w<=5;w++){
  await page.evaluate(()=>window.__fat.pos.set(0,0,-22.3));
  await page.locator('#panel .row').nth(w-1).getByRole('button',{name:'가기'}).click();
  await page.waitForFunction(w=>window.__fat.save.world===w,w);
  if(!(await page.locator('#panel').isHidden())) throw Error('world panel stayed open');
  await page.evaluate(()=>window.__fat.cam(0.5,0.3,1.4));
  await page.waitForTimeout(900);await page.screenshot({path:out+'/'+names[w-2]+'.png'});
  await page.evaluate(w=>{const f=window.__fat,s=f.save,i=w*10-1;s.stage=i;s.weight=f.C.STAGES[i].target;s.plate=20;s.plateStage=i;f.save=s;f.pos.set(0,0,-3);f.cam(Math.PI+0.5,0.25,1.2)},w);
  await page.waitForTimeout(700);await page.screenshot({path:out+'/'+names[w-2]+'-last.png'});
  await page.keyboard.press('KeyE');
  await page.locator('#cert-ok').waitFor({state:'visible'});
  await page.waitForFunction(w=>window.__fat.save.cleared[w-1],w);
  await page.locator('#cert-ok').click();
}
await page.waitForFunction(()=>window.__fat.C.allDone(window.__fat.save));
// 잠긴 포탈은 창이 안 뜬다
const locked=await browser.newPage({viewport:{width:1280,height:760}});
await locked.goto(url.href);await locked.waitForFunction(()=>window.__fat);
await locked.evaluate(()=>{const f=window.__fat,s=f.C.newSave();s.intro=true;f.save=s;f.start();f.pos.set(0,0,-22.3)});
await locked.waitForFunction(()=>document.querySelector('#toast').textContent.includes('10레벨'));
if(!(await locked.locator('#panel').isHidden())) throw Error('locked portal opened');
await locked.close();
const phone=await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true,deviceScaleFactor:1});
phone.on('pageerror',e=>errors.push(String(e)));
await phone.goto(url.href); await phone.waitForFunction(()=>window.__fat);
await phone.screenshot({path:out+'/mobile-menu.png'});
await phone.locator('#m-start').evaluate(e=>e.click());
for(let i=0;i<4;i++)await phone.locator('#story-next').click();
await phone.waitForTimeout(200); await phone.screenshot({path:out+'/mobile.png'});
if(errors.length) throw new Error(errors.join('\n'));
console.log(JSON.stringify({errors,out,checks:['intro','daily','food pickup','click eating','level up','save reload','world 1 certificate','walk-in portal picker','worlds 2-5 certificates','locked portal','mobile controls']},null,2));
await browser.close();
